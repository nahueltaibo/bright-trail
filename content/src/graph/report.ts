import type { Skill } from '@bright-trail/shared';
import { deadEnds, longestChain, roots } from './checks';
import type { GraphBuild } from './pipeline';
import { GENERATOR_MODEL, REVIEWER_MODEL } from './prompts';
import { GRADE_ORDER } from './sources';

const gradeLabel = (grade: Skill['grade']) => (grade === 'K' ? 'Kindergarten' : `Grade ${grade}`);

/** Markdown summary for the owner to skim before content generation. */
export function renderReport(build: GraphBuild): string {
  const { skills, problems, removedTransitive, grades } = build;
  const chain = longestChain(skills);
  const ends = deadEnds(skills);
  const lines: string[] = [
    '# Skill Graph Report',
    '',
    `Generated by \`npm run content:graph\` with ${GENERATOR_MODEL}, reviewed by ${REVIEWER_MODEL}. Don't edit it by hand. Rerun the build instead.`,
    '',
    problems.length === 0
      ? `**All checks pass.** ${skills.length} skills, no cycles, no orphans, and every skill is reachable from a Kindergarten root.`
      : `**${problems.length} problem${problems.length === 1 ? '' : 's'} left, so \`skills.json\` wasn't written.**`,
    '',
  ];

  if (problems.length > 0) {
    lines.push('## Problems', '', ...problems.map((p) => `- ${p.message}`), '');
  }

  lines.push(
    '## Counts',
    '',
    '| Grade | Skills | Reviewer fixes | Rejected fixes | Repairs |',
    '|---|---|---|---|---|',
  );
  for (const grade of GRADE_ORDER) {
    const log = grades.find((g) => g.grade === grade);
    if (!log) continue;
    const count = skills.filter((s) => s.grade === grade).length;
    lines.push(
      `| ${grade} | ${count} | ${log.applied.length} | ${log.rejected.length} | ${log.repairs} |`,
    );
  }
  lines.push(`| **Total** | **${skills.length}** | | | |`, '');

  lines.push(
    '## Shape',
    '',
    `- **Roots:** ${roots(skills)
      .map((s) => `\`${s.id}\``)
      .join(', ')}`,
    `- **Longest chain (${chain.length} skills):** ${chain.map((id) => `\`${id}\``).join(' → ')}`,
    `- **Dead ends below Grade 6 (${ends.length}):** ${ends.map((s) => `\`${s.id}\``).join(', ') || 'none'}. Nothing builds on these, so check that's intended.`,
    `- **Transitive prerequisites removed (${removedTransitive.length}):** ${
      removedTransitive
        .map((r) => `\`${r.skillId}\` no longer lists \`${r.prerequisiteId}\` (via \`${r.via}\`)`)
        .join('; ') || 'none'
    }`,
    '',
  );

  const reviewed = grades.filter(
    (g) => g.applied.length > 0 || g.rejected.length > 0 || g.reviewerNotes,
  );
  if (reviewed.length > 0) {
    lines.push('## Reviewer Changes', '');
    for (const log of reviewed) {
      lines.push(`### ${gradeLabel(log.grade)}`, '');
      if (log.reviewerNotes) lines.push(`${log.reviewerNotes}`, '');
      for (const c of log.applied) lines.push(`- \`${c.skillId}\`: ${c.reason}`);
      for (const r of log.rejected) {
        lines.push(`- Rejected for \`${r.correction.skillId}\`: ${r.correction.reason} (${r.why})`);
      }
      lines.push('');
    }
  }

  lines.push('## Skills', '');
  for (const grade of GRADE_ORDER) {
    const inGrade = skills.filter((s) => s.grade === grade);
    if (inGrade.length === 0) continue;
    lines.push(`### ${gradeLabel(grade)}`, '');
    for (const s of inGrade) {
      const needs = s.prerequisiteIds.length > 0 ? s.prerequisiteIds.join(', ') : 'root';
      lines.push(`- \`${s.id}\` ${s.title} (${s.expectationCodes.join(', ')}). Needs: ${needs}.`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
